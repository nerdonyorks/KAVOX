/**
 * GET /admin/reports/download/excel
 * Generates and downloads Excel workbook
 */
exports.downloadExcelReport = async (req, res) => {
  try {
    const { filter = "daily", startDate, endDate } = req.query;

    const validation = validateDates(filter, startDate, endDate);
    if (!validation.isValid) {
      return res.status(HTTP_STATUS.BAD_REQUEST).send(validation.message);
    }

    const reportData = await reportService.getSalesReportData(filter, startDate, endDate);

    const workbook = new ExcelJS.Workbook();

    // Sheet 1: Sales Summary
    const summarySheet = workbook.addWorksheet("Sales Summary");
    summarySheet.columns = [
      { header: "SALES KPI METRIC", key: "metric", width: 30 },
      { header: "REPORT VALUE", key: "value", width: 25 }
    ];
    summarySheet.addRow({ metric: "Total Placed Orders", value: reportData.summary.totalOrders });
    summarySheet.addRow({ metric: "Gross Sales Revenue", value: reportData.summary.grossSales });
    summarySheet.addRow({ metric: "Product Offer Deductions", value: reportData.summary.productOfferDiscounts });
    summarySheet.addRow({ metric: "Category Offer Deductions", value: reportData.summary.categoryOfferDiscounts });
    summarySheet.addRow({ metric: "Coupon Discounts Deductions", value: reportData.summary.couponDiscounts });
    summarySheet.addRow({ metric: "Total Deductions", value: reportData.summary.discounts });
    summarySheet.addRow({ metric: "Net Revenue Yield", value: reportData.summary.netRevenue });

    // Format headers
    summarySheet.getRow(1).font = { bold: true, color: { argb: "FFFFFFFF" } };
    summarySheet.getRow(1).fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF0F172A" } };

    // Sheet 2: Order Details
    const detailsSheet = workbook.addWorksheet("Order Details");
    detailsSheet.columns = [
      { header: "Order ID", key: "orderId", width: 22 },
      { header: "Date Placed", key: "date", width: 18 },
      { header: "Customer Name", key: "customer", width: 28 },
      { header: "Payment Type", key: "paymentMethod", width: 18 },
      { header: "Gross Sales Amount (INR)", key: "grossAmount", width: 24 },
      { header: "Offer Savings (INR)", key: "offerDiscount", width: 22 },
      { header: "Coupon Savings (INR)", key: "couponDiscount", width: 22 },
      { header: "Net Amount Paid (INR)", key: "finalAmount", width: 24 },
      { header: "Shipping Status", key: "status", width: 18 }
    ];

    reportData.orders.forEach(o => {
      detailsSheet.addRow({
        orderId: o.orderId,
        date: new Date(o.date).toLocaleDateString("en-IN") + " " + new Date(o.date).toLocaleTimeString("en-IN"),
        customer: o.customer,
        paymentMethod: o.paymentMethod,
        grossAmount: o.grossAmount,
        offerDiscount: o.offerDiscount,
        couponDiscount: o.couponDiscount,
        finalAmount: o.finalAmount,
        status: o.status
      });
    });

    detailsSheet.getRow(1).font = { bold: true, color: { argb: "FFFFFFFF" } };
    detailsSheet.getRow(1).fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF0F172A" } };

    // Sheet 3: Analytics Summary
    const analyticsSheet = workbook.addWorksheet("Analytics Summary");
    analyticsSheet.columns = [
      { header: "System Identifier", key: "kpi", width: 30 },
      { header: "Summary Value", key: "value", width: 35 }
    ];
    analyticsSheet.addRow({ kpi: "Brand Store Name", value: "KAVOX SOLE LAB" });
    analyticsSheet.addRow({ kpi: "Report Level Type", value: filter.toUpperCase() });
    analyticsSheet.addRow({ kpi: "Start Date Constraint", value: reportData.dateRange.start.toLocaleString("en-IN") });
    analyticsSheet.addRow({ kpi: "End Date Constraint", value: reportData.dateRange.end.toLocaleString("en-IN") });
    analyticsSheet.addRow({ kpi: "Database Run Date", value: new Date().toLocaleString("en-IN") });
    analyticsSheet.addRow({ kpi: "Total Orders Captured", value: reportData.summary.totalOrders });
    analyticsSheet.addRow({ kpi: "Gross Sales Sum", value: reportData.summary.grossSales });
    analyticsSheet.addRow({ kpi: "Offers Total Discount", value: reportData.summary.offerDiscounts });
    analyticsSheet.addRow({ kpi: "Coupon Total Discount", value: reportData.summary.couponDiscounts });
    analyticsSheet.addRow({ kpi: "Net Revenue Total", value: reportData.summary.netRevenue });

    analyticsSheet.getRow(1).font = { bold: true, color: { argb: "FFFFFFFF" } };
    analyticsSheet.getRow(1).fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF0F172A" } };

    res.setHeader("Content-Type", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
    res.setHeader("Content-Disposition", `attachment; filename="KAVOX-sales-report-${filter}-${Date.now()}.xlsx"`);

    await workbook.xlsx.write(res);
    res.end();
  } catch (error) {
    console.error("Excel Download Controller Error:", error);
    res.status(HTTP_STATUS.INTERNAL_SERVER_ERROR).send("Failed to export Excel sheet.");
  }
};
