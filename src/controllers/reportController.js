/**
 * Sales Report Controller
 * ───────────────────────
 * Renders sales dashboards, provides metric endpoints, and exports
 * clean, styled PDF (via pdfkit) and Excel (via exceljs) files.
 */

const reportService = require("../services/reportService");
const PDFDocument = require("pdfkit");
const ExcelJS = require("exceljs");
const { HTTP_STATUS } = require("../utils/constants");

// Validate Date Range constraints
function validateDates(filter, startDate, endDate) {
  if (filter === "custom") {
    if (!startDate || !endDate) {
      return { isValid: false, message: "Both Start Date and End Date are required." };
    }

    const start = new Date(startDate);
    const end = new Date(endDate);
    const today = new Date();

    if (isNaN(start.getTime()) || isNaN(end.getTime())) {
      return { isValid: false, message: "Invalid date format." };
    }

    if (end < start) {
      return { isValid: false, message: "End date cannot be earlier than start date." };
    }

    if (start > today || end > today) {
      return { isValid: false, message: "Future dates are not allowed." };
    }
  }
  return { isValid: true };
}

/**
 * Renders the Reports page view
 */
exports.renderReportDashboard = async (req, res) => {
  try {
    res.render("admin/report", {
      title: "Sales Report - KAVOX Admin",
      activePage: "report"
    });
  } catch (error) {
    console.error("Render Report Dashboard Error:", error);
    res.status(HTTP_STATUS.INTERNAL_SERVER_ERROR).send("Failed to render reports page.");
  }
};

/**
 * GET /admin/reports/summary
 * Returns analytics card counts and chart trends
 */
exports.getReportSummaryAPI = async (req, res) => {
  try {
    const { filter = "daily", startDate, endDate } = req.query;

    const validation = validateDates(filter, startDate, endDate);
    if (!validation.isValid) {
      return res.status(HTTP_STATUS.BAD_REQUEST).json({ success: false, message: validation.message });
    }

    const data = await reportService.getAnalyticsData(filter, startDate, endDate);
    res.status(HTTP_STATUS.OK).json({ success: true, data });
  } catch (error) {
    console.error("Get Report Summary Error:", error);
    res.status(HTTP_STATUS.INTERNAL_SERVER_ERROR).json({
      success: false,
      message: "Failed to load report summaries."
    });
  }
};

/**
 * GET /admin/reports/sales
 * Returns order details list with pagination
 */
exports.getReportSalesAPI = async (req, res) => {
  try {
    const { filter = "daily", startDate, endDate } = req.query;
    const page = parseInt(req.query.page) || 1;
    const limit = 10;
    const skip = (page - 1) * limit;

    const validation = validateDates(filter, startDate, endDate);
    if (!validation.isValid) {
      return res.status(HTTP_STATUS.BAD_REQUEST).json({ success: false, message: validation.message });
    }

    const reportData = await reportService.getSalesReportData(filter, startDate, endDate);
    
    // Paginate orders in JS to preserve exact sorting
    const paginatedOrders = reportData.orders.slice(skip, skip + limit);
    const totalPages = Math.ceil(reportData.orders.length / limit) || 1;

    res.status(HTTP_STATUS.OK).json({
      success: true,
      orders: paginatedOrders,
      summary: reportData.summary,
      page,
      totalPages
    });
  } catch (error) {
    console.error("Get Report Sales Error:", error);
    res.status(HTTP_STATUS.INTERNAL_SERVER_ERROR).json({
      success: false,
      message: "Failed to load sales rows."
    });
  }
};

